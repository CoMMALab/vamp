# Extract representative MBM environments (sphere/cylinder/box primitives) for each robot from
# the problem tarballs and emit mbm_envs.hh for the C++ harness. Samples a few scenes per problem
# set so the real obstacle geometry (and its clearance distribution) is exercised.
import sys, re, tarfile
from pathlib import Path
from collections import defaultdict
import numpy as np
from yaml import load
try:
    from yaml import CLoader as Loader
except ImportError:
    from yaml import Loader
from vamp.transformations import (euler_from_matrix, identity_matrix, quaternion_matrix,
                                  translation_from_matrix, translation_matrix)

RES = Path(__file__).resolve().parents[3] / "resources"
SCENES_PER_SET = 3   # sampled scenes per problem set

def tf_from_yaml(t):
    T = translation_matrix(t['position']); T[:3, :3] = quaternion_matrix(t['orientation'])[:3, :3]; return T

def parse_scene(data):
    prims = []
    for co in data['world']['collision_objects']:
        base = identity_matrix() if 'pose' not in co else tf_from_yaml(co['pose'])
        prim = co['primitives'][0]
        pose = np.dot(base, tf_from_yaml(co['primitive_poses'][0]))
        pos = translation_from_matrix(pose).tolist()
        eul = list(euler_from_matrix(pose))
        t = prim['type']; d = prim['dimensions']
        if t == 'sphere':                      # kind 0: r=a
            prims.append((0, *pos, 0, 0, 0, d[0], 0, 0))
        elif t == 'cylinder':                  # kind 1: euler, r=a, len=b   (len=d[0], r=d[1])
            prims.append((1, *pos, *eul, d[1], d[0], 0))
        elif t == 'box':                       # kind 2: euler, half_extents=a,b,c
            prims.append((2, *pos, *eul, d[0] / 2, d[1] / 2, d[2] / 2))
    return prims

def cxx(v): return "%.6g" % v

hdr = ["// generated by dump_mbm_envs.py: representative MBM environments per robot",
       "#pragma once", "#include <vector>", "",
       "// kind: 0=sphere(r=a) 1=cylinder(euler ex,ey,ez; r=a,len=b) 2=box(euler; half=a,b,c)",
       "struct MbmPrim { int kind; float px,py,pz, ex,ey,ez, a,b,c; };",
       "struct MbmEnv { const char* name; std::vector<MbmPrim> prims; };", ""]

for robot in ["ur5", "panda", "fetch", "baxter"]:
    tar = tarfile.open(RES / robot / "problems.tar.bz2", "r:bz2")
    by_set = defaultdict(list)
    for m in tar.getmembers():
        if m.isfile() and "scene" in m.name:
            pset = m.name.split('/')[1]
            by_set[pset].append(m)
    envs = []
    for pset, members in sorted(by_set.items()):
        members.sort(key=lambda m: m.name)
        for m in members[:SCENES_PER_SET]:
            prims = parse_scene(load(tar.extractfile(m).read(), Loader=Loader))
            if prims:
                idx = re.findall(r'\d+', m.name.split('/')[-1])[0]
                envs.append((f"{pset}#{idx}", prims))
    body = []
    for name, prims in envs:
        plist = ",".join("{%d,%s}" % (p[0], ",".join(cxx(x) for x in p[1:])) for p in prims)
        body.append('{"%s",{%s}}' % (name, plist))
    hdr.append(f"static const std::vector<MbmEnv> {robot}_envs = {{{','.join(body)}}};")
    print(f"{robot}: {len(envs)} envs, "
          f"{sum(len(p) for _, p in envs)} prims across {len(by_set)} problem sets")

(Path(__file__).parent / "mbm_envs.hh").write_text("\n".join(hdr) + "\n")
print("-> mbm_envs.hh")
