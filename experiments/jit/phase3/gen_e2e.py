# Generate PandaE / FetchE headers (cricket-native fkcc_pretrig, leaf-trig hoisted to ps/pc)
# for m30, plus link_groups.hh (leaf-sphere indices per collision link) for m33.
# Writes panda_e.hh / fetch_e.hh / link_groups.hh next to this script.
#   micromamba run -n jit_patch python gen_e2e.py
import cricket
from pathlib import Path
res = cricket.resources_dir()
out = Path(__file__).parent
groups_hh = ["// generated by gen_e2e.py: leaf-sphere indices per collision link", "#pragma once",
             "#include <vector>", ""]


def gen(name, rdir, urdf, srdf, eef, fn, gvar):
    base = res / rdir
    o = cricket.GenOptions(
        urdf=str(base / urdf), srdf=str(base / srdf), end_effector=eef,
        template_path=str(res / "templates/fk_template.hh"),
        subtemplates={"ccfk": str(res / "templates/ccfk_template.hh")},
        data={"name": name, "resolution": 32})
    r = cricket.generate_robot_source(o)
    (out / fn).write_text(r.source)
    groups = [g for g in r.data["per_link_spheres"] if g]   # non-empty = links with geometry
    body = ",".join("{" + ",".join(map(str, g)) + "}" for g in groups)
    groups_hh.append(f"static const std::vector<std::vector<int>> {gvar} = {{{body}}};")
    print(f"{name}: fkcc_pretrig={'fkcc_pretrig' in r.source} "
          f"sphere_fk_pretrig={'sphere_fk_pretrig' in r.source} "
          f"ns={r.n_spheres} dim={r.dimension} links={len(groups)} -> {fn}")


gen("PandaE", "panda", "panda_spherized.urdf", "panda.srdf", "panda_grasptarget", "panda_e.hh", "panda_links")
gen("FetchE", "fetch", "fetch_spherized.urdf", "fetch.srdf", "gripper_link", "fetch_e.hh", "fetch_links")
(out / "link_groups.hh").write_text("\n".join(groups_hh) + "\n")
print("-> link_groups.hh")
