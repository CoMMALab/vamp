# Dump full MBM problems (env prims + start + goals, joint-ordered) for ur5/panda/fetch/baxter
# into mbm_problems.hh for the standalone RRTC benchmark. Joint order from cricket (matches the
# generated robot's config order); YAML parsed with the same helpers as the tar->pkl converter.
import sys, re, tarfile
from pathlib import Path
from collections import defaultdict
import numpy as np
import cricket
from yaml import load
try:
    from yaml import CLoader as Loader
except ImportError:
    from yaml import Loader

REPO = Path(__file__).resolve().parents[3]
RES = REPO / "resources"
sys.path.insert(0, str(RES))
from problem_tar_to_pkl_json import load_moveit_yaml_scene, load_moveit_yaml_request  # noqa

K_PER_SET = 20
ROBOTS = [
    ("ur5", "ur5_spherized.urdf", "ur5.srdf", "robotiq_85_base_link"),
    ("panda", "panda_spherized.urdf", "panda.srdf", "panda_grasptarget"),
    ("fetch", "fetch_spherized.urdf", "fetch.srdf", "gripper_link"),
    ("baxter", "baxter_spherized.urdf", "baxter.srdf", "right_gripper"),
]


def joint_order(rdir, urdf, srdf, ee):
    o = cricket.GenOptions(urdf=str(RES / rdir / urdf), srdf=str(RES / rdir / srdf), end_effector=ee,
        template_path=str(cricket.resources_dir() / "templates/fk_template.hh"),
        subtemplates={"ccfk": str(cricket.resources_dir() / "templates/ccfk_template.hh")},
        data={"name": rdir, "resolution": 32})
    r = cricket.generate_robot_source(o)
    return r.data["joint_names"], r.dimension


def env_prims(scene):
    prims = []
    for o in scene["sphere"]:
        prims.append((0, *o["position"], 0, 0, 0, o["radius"], 0, 0))
    for o in scene["cylinder"]:
        e = o["orientation_euler_xyz"]; prims.append((1, *o["position"], e[0], e[1], e[2], o["radius"], o["length"], 0))
    for o in scene["box"]:
        e = o["orientation_euler_xyz"]; h = o["half_extents"]; prims.append((2, *o["position"], e[0], e[1], e[2], h[0], h[1], h[2]))
    return prims


hdr = ["// generated by dump_mbm_problems.py: full MBM problems for the standalone RRTC bench",
       "#pragma once", "#include <vector>", "",
       "struct PPrim { int kind; float px,py,pz, ex,ey,ez, a,b,c; };",
       "struct MbmProb { const char* name; std::vector<float> start; std::vector<std::vector<float>> goals; std::vector<PPrim> prims; };", ""]


def cxx(v):
    return "%.7g" % v


for tag, urdf, srdf, ee in ROBOTS:
    joints, dim = joint_order(tag, urdf, srdf, ee)
    tar = tarfile.open(RES / tag / "problems.tar.bz2", "r:bz2")
    scenes, requests = defaultdict(dict), defaultdict(dict)
    for m in tar.getmembers():
        if not m.isfile():
            continue
        pset, fname = m.name.split('/')[1], m.name.split('/')[-1]
        pset = pset.replace(f"_{tag}", "")
        idx = int(re.findall(r'\d+', fname)[0])
        data = load(tar.extractfile(m).read(), Loader=Loader)
        if "scene" in fname:
            scenes[pset][idx] = load_moveit_yaml_scene(data)
        elif "request" in fname:
            requests[pset][idx] = load_moveit_yaml_request(data, joints)
    probs = []
    for pset in sorted(scenes):
        common = sorted(set(scenes[pset]) & set(requests[pset]))
        for idx in common[:K_PER_SET]:
            req = requests[pset][idx]
            if len(req["start"]) != dim or any(len(g) != dim for g in req["goals"]):
                continue
            probs.append((f"{pset}#{idx}", req["start"], req["goals"], env_prims(scenes[pset][idx])))
    body = []
    for name, start, goals, prims in probs:
        s = ",".join(cxx(x) for x in start)
        g = ",".join("{" + ",".join(cxx(x) for x in gg) + "}" for gg in goals)
        p = ",".join("{%d,%s}" % (pr[0], ",".join(cxx(x) for x in pr[1:])) for pr in prims)
        body.append('{"%s",{%s},{%s},{%s}}' % (name, s, g, p))
    hdr.append(f"static const std::vector<MbmProb> {tag}_probs = {{{','.join(body)}}};")
    print(f"{tag}: dim={dim} joints={len(joints)} problems={len(probs)}")

(Path(__file__).parent / "mbm_problems.hh").write_text("\n".join(hdr) + "\n")
print("-> mbm_problems.hh")
