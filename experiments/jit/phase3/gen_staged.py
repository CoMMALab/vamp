# Emit staged_place.hh: per-sphere placement rows (slot, lx, ly, lz, radius) for leaves and
# bounding spheres, for panda/fetch/baxter, from cricket's leaf_place / bsphere_place data.
# Robot headers (panda_e.hh etc., now with joint_tf/place_sphere) come from gen_e2e.py.
import cricket
from pathlib import Path
res = cricket.resources_dir()
out = Path(__file__).parent
hdr = ["// generated by gen_staged.py: per-sphere placement rows for the staged FK",
       "#pragma once", "#include <vector>", "",
       "struct Place { unsigned slot; float lx, ly, lz, r; };", ""]


def emit(name, rdir, urdf, srdf, ee, tag):
    o = cricket.GenOptions(urdf=str(res / rdir / urdf), srdf=str(res / rdir / srdf), end_effector=ee,
        template_path=str(res / "templates/fk_template.hh"),
        subtemplates={"ccfk": str(res / "templates/ccfk_template.hh")},
        data={"name": name, "resolution": 32})
    r = cricket.generate_robot_source(o)
    d = r.data
    def rows(key):
        return ",".join("{%d,%.9g,%.9g,%.9g,%.9g}" % (int(x[0]), x[1], x[2], x[3], x[4]) for x in d[key])
    hdr.append(f"static const std::vector<Place> {tag}_leaf = {{{rows('leaf_place')}}};")
    hdr.append(f"static const std::vector<Place> {tag}_bsph = {{{rows('bsphere_place')}}};")
    print(f"{name}: joint_tf={'joint_tf' in r.source} n_joint_tf={d['n_joint_tf']} "
          f"leaves={len(d['leaf_place'])} bsph={len(d['bsphere_place'])}")


emit("PandaE", "panda", "panda_spherized.urdf", "panda.srdf", "panda_grasptarget", "panda")
emit("FetchE", "fetch", "fetch_spherized.urdf", "fetch.srdf", "gripper_link", "fetch")
emit("BaxterE", "baxter", "baxter_spherized.urdf", "baxter.srdf", "right_gripper", "baxter")
(out / "staged_place.hh").write_text("\n".join(hdr) + "\n")
print("-> staged_place.hh")
